import random

import pytest

from tracesim.calibrate import fit_descriptor, fit_report, restrict
from tracesim.device import DeviceDescriptor, OpClassModel
from tracesim.simulator import forward_cost
from tracesim.trace import Op

INFO = {"cores": 2, "smt": 2, "llc": 8 << 20, "l1d": 0, "l2": 0, "simd": "", "cpu": "test"}


def truth() -> DeviceDescriptor:
    gemm = OpClassModel(unit="flops", rate={"float32": 4e10, "float64": 2e10},
                        call_overhead_s=8e-6, serial_fraction=0.15, fork_overhead_s=4e-6,
                        smt_yield=0.3)
    ew = OpClassModel(unit="elements", rate={"float32": 2e9, "float64": 1e9},
                      call_overhead_s=3e-6, serial_fraction=0.4, fork_overhead_s=2e-6,
                      smt_yield=0.1)
    return DeviceDescriptor(name="truth", cores=2, smt=2, cache_bytes=8 << 20,
                            mem_bandwidth_bytes_per_s=1.2e10, mem_serial_fraction=0.6,
                            first_touch_bytes_per_s=3e9,
                            op_classes={"gemm": gemm, "ew_cheap": ew})


def synthetic_points(noise: float = 0.0, seed: int = 0) -> list[dict]:
    """Microbenchmark points generated by a known device, optionally with timing noise."""
    device, rng, points = truth(), random.Random(seed), []

    def add(bench, op_class, work, read, written, dtype, threads):
        op = Op(name="p", kind="k", op_class=op_class, in_shapes=[], out_shape=[],
                dtype=dtype, work=work, bytes_read=read, bytes_written=written)
        t = forward_cost(op, device.op_classes[op_class], device, threads).total
        t *= 1.0 + rng.uniform(-noise, noise)
        back = t * 2.0 if threads == 1 else None
        points.append({"id": f"{bench}-{work}", "bench": bench, "op_class": op_class,
                       "kind": "k", "dtype": dtype, "threads": threads, "work": work,
                       "items": 1, "bytes_read": read, "bytes_written": written, "t": t,
                       "t_fb": back, "t_fb_noin": None})

    for dtype, size in (("float32", 4), ("float64", 8)):
        for threads in (1, 2, 4):
            for work in (1e4, 1e5, 1e6, 1e7, 1e8, 1e9, 1e10):
                add("gemm", "gemm", work, 4096, 4096, dtype, threads)
            for n in (1e3, 1e4, 1e5, 1e6, 3e6):
                add("ew_cheap", "ew_cheap", n, int(n * size), int(n * size), dtype, threads)
            for n in (2e6, 3e6, 16e6, 32e6):
                add("stream", "ew_cheap", n, int(2 * n * size), int(n * size), dtype, threads)
    return points


def test_fit_recovers_a_known_device_from_clean_points():
    fitted = fit_descriptor(synthetic_points(), info=INFO)
    want = truth()
    assert fitted.mem_bandwidth_bytes_per_s == pytest.approx(1.2e10, rel=0.02)
    assert fitted.mem_serial_fraction == pytest.approx(0.6, abs=0.02)
    assert fitted.first_touch_bytes_per_s == pytest.approx(3e9, rel=0.05)
    for cls in ("gemm", "ew_cheap"):
        got, exp = fitted.op_classes[cls], want.op_classes[cls]
        assert got.rate["float32"] == pytest.approx(exp.rate["float32"], rel=0.03)
        assert got.rate["float64"] == pytest.approx(exp.rate["float64"], rel=0.03)
        assert got.call_overhead_s == pytest.approx(exp.call_overhead_s, rel=0.05)
        assert got.serial_fraction == pytest.approx(exp.serial_fraction, abs=0.03)
        assert got.smt_yield == pytest.approx(exp.smt_yield, abs=0.05)
        assert got.backward_ratio == pytest.approx(1.0, abs=0.05)


def test_fit_is_stable_under_timing_noise():
    points = synthetic_points(noise=0.15, seed=3)
    fitted = fit_descriptor(points, info=INFO)
    assert fitted.op_classes["gemm"].rate["float32"] == pytest.approx(4e10, rel=0.15)
    report = fit_report(points, fitted)
    assert report["gemm"]["mape"] < 0.15
    assert report["ew_cheap"]["points"] == 30


def test_restrict_by_threads_leaves_the_hyperthread_yield_unknown():
    points = synthetic_points()
    kept = restrict(points, max_threads=2)
    assert {p["threads"] for p in kept} == {1, 2}
    fitted = fit_descriptor(points, info=INFO, max_threads=2)
    assert fitted.op_classes["gemm"].smt_yield == 0.0
    assert fitted.op_classes["gemm"].serial_fraction == pytest.approx(0.15, abs=0.03)
    assert fitted.calibration["max_threads"] == 2


def test_restrict_by_size_drops_large_operators_but_keeps_the_bandwidth_points():
    points = synthetic_points()
    kept = restrict(points, max_work={"gemm": 1e7, "ew_cheap": 1e4})
    assert max(p["work"] for p in kept if p["bench"] == "gemm") == 1e7
    # ew_cheap is capped below its fourth-smallest size, so the floor of four sizes applies.
    assert sorted({p["work"] for p in kept if p["bench"] == "ew_cheap"}) == [1e3, 1e4, 1e5, 1e6]
    assert len([p for p in kept if p["bench"] == "stream"]) == 24
    fitted = fit_descriptor(points, info=INFO, max_work={"gemm": 1e7, "ew_cheap": 1e4})
    assert fitted.calibration["restricted_by_size"] is True
    assert fitted.op_classes["gemm"].rate["float32"] == pytest.approx(4e10, rel=0.05)
